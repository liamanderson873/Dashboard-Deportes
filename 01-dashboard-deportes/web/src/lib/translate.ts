/** Spanish position; unknown values fall back to the group's singular, then raw. */
export function positionLabel(position: string | null): string | null {
  if (position === null) return null;
  const known = POSITIONS_ES[position];
  if (known) return known;
  const group = positionGroup(position);
  return group === "unknown" ? position : es.team.squad.groupSingular[group];
}

export function nationalityLabel(name: string | null): string | null {
  if (name === null) return null;
  return NATIONALITIES_ES[name] ?? name;
}

export function clubColorsLabel(raw: string | null): string | null {
  if (raw === null) return null;
  return raw
    .split("/")
    .map((w) => w.trim())
    .filter((w) => w !== "")
    .map((w) => CLUB_COLORS_ES[w] ?? w)
    .join(" / ");
}
